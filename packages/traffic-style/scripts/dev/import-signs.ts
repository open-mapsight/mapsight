#!/usr/bin/env node
import {mkdir, readFile, readdir, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const packageRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"../..",
);
const sourceDir = path.join(packageRoot, "src/icons");
const outputPath = path.join(packageRoot, "src/generated/signs.ts");
const variants = ["default", "small", "xsmall", "plain"] as const;
const sizes = {default: 40, small: 28, xsmall: 22, plain: 34};

type MetaIcon = {render?: string; groups?: string[]; fallback?: string};
const meta = JSON.parse(
	await readFile(path.join(packageRoot, "src/meta.json"), "utf8"),
) as {
	icons: Record<string, MetaIcon>;
};
const files = new Set(await readdir(sourceDir));
const layers: string[] = [];
const layerIds = new Map<string, number>();
const signs: Record<string, Record<string, number[]>> = {};

// These roles describe the authored sign palette, not arbitrary SVG colors.
function colorRole(
	kind: string,
	color: string,
	tag: string,
	filledBase: boolean,
): string | undefined {
	if (kind === "stroke") {
		return color === "#b80707" ? "border" : undefined;
	}
	if (["#035799", "#b80707", "#ffca4f"].includes(color)) {
		return "background";
	}
	if (["#000", "#000000", "#f8f8f8"].includes(color)) {
		return "foreground";
	}
	if (
		["#fff", "#ffffff"].includes(color) &&
		!/stroke="#000(?:000)?"/.test(tag)
	) {
		return filledBase ? "foreground" : "background";
	}
	// Lamp colors and the outer visibility outlines deliberately remain fixed.
	return undefined;
}

function parameterizeLayer(markup: string, filledBase: boolean): string {
	return markup.replace(/<[^>]+>/g, (tag) =>
		tag.replace(
			/\b(fill|stroke)="(#[a-f\d]+)"/gi,
			(attribute, kind: string, color: string) => {
				const role = colorRole(kind, color, tag, filledBase);
				return role ? `${kind}="{{${role}:${color}}}"` : attribute;
			},
		),
	);
}

for (const [id, icon] of Object.entries(meta.icons).sort(([left], [right]) =>
	left.localeCompare(right),
)) {
	if (
		icon.render !== "sprite" ||
		!icon.groups?.some(
			(group) => group === "traffic" || group === "poi-parking",
		)
	) {
		continue;
	}
	const recipes: Record<string, number[]> = {};
	for (const variant of variants) {
		let sourceId = id;
		const visited = new Set<string>();
		while (!files.has(`${sourceId}-${variant}.svg`)) {
			if (visited.has(sourceId) || !meta.icons[sourceId]?.fallback) {
				throw new Error(`Missing sign variant: ${id}-${variant}`);
			}
			visited.add(sourceId);
			sourceId = meta.icons[sourceId]!.fallback!;
		}
		const svg = await readFile(
			path.join(sourceDir, `${sourceId}-${variant}.svg`),
			"utf8",
		);
		const size = sizes[variant];
		if (!svg.includes(`viewBox="0 0 ${size} ${size}"`)) {
			throw new Error(
				`Unexpected sign dimensions: ${sourceId}-${variant}`,
			);
		}
		const inner = svg
			.replace(/^[\s\S]*?<svg\b[^>]*>/, "")
			.replace(/<\/svg>\s*$/, "")
			.trim()
			.replace(
				/^<g fill="none" fill-rule="evenodd">([\s\S]*)<\/g>$/,
				"$1",
			)
			.replace(/>\s+</g, "><")
			.trim();
		// These controlled source SVGs contain self-closing shapes and at most one nested group.
		const parts =
			inner.match(
				/<g\b[^>]*>[\s\S]*?<\/g>|<(?:path|circle|rect)\b[^>]*\/>/g,
			) ?? [];
		if (parts.join("") !== inner) {
			throw new Error(`Unsupported sign markup: ${sourceId}-${variant}`);
		}
		const filledBase = /fill="#(?:035799|b80707|ffca4f)"/.test(inner);
		recipes[variant] = parts.map((part) => {
			const layer = parameterizeLayer(part, filledBase);
			let layerId = layerIds.get(layer);
			if (layerId === undefined) {
				layerId = layers.length;
				layers.push(layer);
				layerIds.set(layer, layerId);
			}
			return layerId;
		});
	}
	signs[id] = recipes;
}

await mkdir(path.dirname(outputPath), {recursive: true});
await writeFile(
	outputPath,
	[
		'import type {IconVariant} from "../lib/icon/icon-id.ts";',
		"",
		"/** Generated by scripts/dev/import-signs.ts — do not edit manually. */",
		`export const signLayers: string[] = ${JSON.stringify(layers, null, "\t")};`,
		`export const signRecipes: Record<string, Record<IconVariant, number[]>> = ${JSON.stringify(signs, null, "\t")};`,
		"",
	].join("\n"),
);
console.log(
	`Wrote ${Object.keys(signs).length} signs using ${layers.length} shared layers to ${outputPath}`,
);
